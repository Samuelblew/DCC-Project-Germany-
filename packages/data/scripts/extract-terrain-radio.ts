/**
 * Extracts airfield radio frequencies and approach NDBs from a DCS terrain into a data file.
 *
 *   bun scripts/extract-terrain-radio.ts "D:/DCS/DCS World" GermanyColdWar germany-cold-war
 *
 * Reads Mods/terrains/<terrain>/Radio.lua (tower frequencies) and Beacons.lua (airport and
 * approach homers), and writes src/theatres/<theatre>/airdrome-radio.ts keyed by airfield name.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const [dcsRoot, terrain, theatreDir] = process.argv.slice(2)
if (!dcsRoot || !terrain || !theatreDir) {
  console.error('usage: extract-terrain-radio <dcs root> <terrain folder> <theatre dir>')
  process.exit(1)
}

const terrainDir = join(dcsRoot, 'Mods', 'terrains', terrain)
const radioLua = readFileSync(join(terrainDir, 'Radio.lua'), 'utf8')
const beaconsLua = readFileSync(join(terrainDir, 'Beacons.lua'), 'utf8')
const airdromeIds = loadAirdromeIds(
  join(import.meta.dir, '..', 'src', 'theatres', theatreDir, 'airdrome-details.ts')
)

function loadAirdromeIds(path: string) {
  const source = readFileSync(path, 'utf8')
  const ids = new Map<number, string>()
  for (const match of source.matchAll(/\n  "([^"]+)": \{\n    "id": (\d+),/g)) {
    ids.set(Number(match[2]), match[1]!)
  }
  return ids
}

/** Splits a Lua array of `{ ... };` records into their bodies. */
function records(lua: string) {
  return lua.split(/\n\t\{\n/).slice(1)
}

type Radio = { callsign: string; uhf?: number; vhf?: number }
const radios = new Map<string, Radio>()
for (const body of records(radioLua)) {
  const id = body.match(/radioId = 'airfield(\d+)_0'/)?.[1]
  const name = id ? airdromeIds.get(Number(id)) : undefined
  if (!name) continue
  const callsign = body.match(/\["common"\] = \{_\("([^"]*)"\)/)?.[1] ?? name
  const band = (key: string) => {
    const hz = body.match(new RegExp(`\\[${key}\\] = \\{MODULATIONTYPE_\\w+, ([\\d.]+)\\}`))?.[1]
    return hz ? Math.round(Number(hz) / 1_000) / 1_000 : undefined
  }
  radios.set(name, { callsign, uhf: band('UHF'), vhf: band('VHF_HI') })
}

type Homer = {
  airfield: string
  kind: 'far' | 'near'
  khz: number
  callsign: string
  heading: number
  x: number
  y: number
}
const homers: Homer[] = []
for (const body of records(beaconsLua)) {
  const type = body.match(/type = BEACON_TYPE_(\w+);/)?.[1]
  const kind = type === 'ILS_FAR_HOMER' ? 'far' : type === 'ILS_NEAR_HOMER' ? 'near' : undefined
  const id = body.match(/beaconId = 'airfield(\d+)_\d+'/)?.[1]
  const airfield = id ? airdromeIds.get(Number(id)) : undefined
  if (!kind || !airfield) continue
  const position = body.match(/position = \{ ([-\d.]+), [-\d.]+, ([-\d.]+) \}/)
  homers.push({
    airfield,
    kind,
    khz: Math.round(Number(body.match(/frequency = ([\d.]+);/)?.[1]) / 1_000),
    callsign: body.match(/callsign = '([^']*)'/)?.[1] ?? '',
    heading: (Math.round(Number(body.match(/direction = ([-\d.]+);/)?.[1] ?? 0)) + 360) % 360,
    x: Number(position?.[1]),
    y: Number(position?.[2])
  })
}

/** Pairs each outer marker with the inner marker of the same approach (same heading, nearest). */
function approaches(airfield: string) {
  const own = homers.filter((homer) => homer.airfield === airfield)
  return own
    .filter((homer) => homer.kind === 'far')
    .map((outer) => {
      const inner = own
        .filter((homer) => homer.kind === 'near' && Math.abs(homer.heading - outer.heading) <= 2)
        .sort(
          (a, b) =>
            Math.hypot(a.x - outer.x, a.y - outer.y) - Math.hypot(b.x - outer.x, b.y - outer.y)
        )[0]
      return {
        heading: outer.heading,
        outer: { khz: outer.khz, callsign: outer.callsign },
        ...(inner ? { inner: { khz: inner.khz, callsign: inner.callsign } } : {})
      }
    })
    .sort((a, b) => a.heading - b.heading)
}

const names = [...new Set([...radios.keys(), ...homers.map((homer) => homer.airfield)])].sort()
const entries = Object.fromEntries(
  names.map((name) => [
    name,
    { ...(radios.get(name) ? { radio: radios.get(name) } : {}), approaches: approaches(name) }
  ])
)

const out = join(import.meta.dir, '..', 'src', 'theatres', theatreDir, 'airdrome-radio.ts')
writeFileSync(
  out,
  `import type { AirdromeRadio } from '../airdrome-radio'

// Generated by scripts/extract-terrain-radio.ts from the DCS ${terrain} terrain. Do not edit by hand.
export const airdromeRadio: Record<string, AirdromeRadio> = ${JSON.stringify(entries, null, 2)}
`
)
console.log(
  `${names.length} airfields, ${radios.size} with tower frequencies, ${homers.length} approach homers -> ${out}`
)
